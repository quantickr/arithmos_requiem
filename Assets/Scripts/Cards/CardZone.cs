namespace ArithmosRequiem.Cards
{
    /// <summary>Зона, в которой находится карта во время боя.</summary>
    public enum CardZone
    {
        Deck,     // личная колода (тянем отсюда)
        Hand,     // рука
        Discard,  // сброс (перемешивается в колоду, когда та пуста)
        Exiled,   // изгнана до конца боя
        Removed   // удалена навсегда
    }

    /// <summary>Тип карты по механике сброса и разыгрыша.</summary>
    public enum CardKind
    {
        Numbered, // обычная игральная карта
        Action,   // карта действия (даёт кость на 1 ход; «Когда»-действия сбрасываются в конце хода)
        Starting  // стартовая карта
    }

    /// <summary>Модель срабатывания эффекта карты.</summary>
    public enum CardCondition
    {
        None, // безусловный эффект
        If,   // «Если»: разыгрывается только при условии, эффект одноразовый
        When  // «Когда»: постоянный триггер в течение хода
    }
}
